#!/usr/bin/env bash
# The screenshot stand (#191): runs ScreenshotTest on the connected emulator and pulls the shots
# into docs/screenshots/<locale>/, then rebuilds the gallery page.
#
#   scripts/screenshots.sh            # ru
#   scripts/screenshots.sh en         # en
#
# Needs an emulator (not a phone with a real diary: the test runs on the .debug app, but it is still
# your device) - `adb devices` must list exactly one.
set -euo pipefail

locale="${1:-ru}"
app_id="com.neojelll.diaxtracker.debug"
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/docs/screenshots/$locale"
remote="/sdcard/Android/data/$app_id/files/screenshots/$locale"

cd "$root"
# Installed and run by hand rather than through connectedAndroidTest, which uninstalls the app -
# and the shots with it - as soon as the run ends.
./gradlew -q :app:installDebug :app:installDebugAndroidTest
adb shell rm -rf "$remote" >/dev/null 2>&1 || true
result="$(adb shell am instrument -w -r \
  -e class com.neojelll.diaxtracker.screenshots.ScreenshotTest \
  -e screenshotLocale "$locale" \
  "$app_id.test/androidx.test.runner.AndroidJUnitRunner")"
if ! grep -q "^OK (" <<<"$result"; then
  echo "$result" | grep -E "INSTRUMENTATION_STATUS: (test|stack)=|FAILURES|Tests run" | head -40
  echo "Screenshot test failed" >&2
  exit 1
fi
echo "$result" | grep "^OK ("

rm -rf "$out" && mkdir -p "$out"
adb pull "$remote/." "$out" >/dev/null
count=$(find "$out" -name '*.png' | wc -l | tr -d ' ')
echo "Pulled $count shots into docs/screenshots/$locale"

# Gallery: every shot, in scenario order.
gallery="$root/docs/screenshots/README.md"
{
  echo "# Screenshots"
  echo
  echo "Generated by \`scripts/screenshots.sh\` from demo data (\`ScreenshotTest\`, \`DemoFixtures\`) - no real diary."
  for dir in "$root"/docs/screenshots/*/; do
    lang="$(basename "$dir")"
    echo
    echo "## $lang"
    echo
    for png in $(ls "$dir"*.png | sort); do
      name="$(basename "$png" .png)"
      echo "<img src=\"$lang/$name.png\" width=\"240\" alt=\"$name\">"
    done
  done
} > "$gallery"
echo "Gallery: docs/screenshots/README.md"
